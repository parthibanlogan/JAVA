// CivilTech Innovation Starter: page logic.
// Flow: read inputs -> call the Java function calculate() -> draw cards, charts, map, 3D, table.
import { calculate } from './java/app.js';          // generated by TeaVM from src/main/java/app/WebApi.java
import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';

const $ = id => document.getElementById(id);
const fmt = (x, d = 1) => Number(x).toLocaleString('en-IN', { minimumFractionDigits: d, maximumFractionDigits: d });
let timeChart, barChart, map, markers, scene3d;

async function loadSamples() {
  $('sub-csv').value = await (await fetch('data/subcatchments.csv')).text();
  $('rain-csv').value = await (await fetch('data/rainfall_fengal_2024.csv')).text();
}

function readFileInto(input, textarea) {
  input.addEventListener('change', () => {
    const f = input.files[0];
    if (!f) return;
    const r = new FileReader();
    r.onload = () => { textarea.value = r.result; run(); };
    r.readAsText(f);
  });
}

function run() {
  const t0 = performance.now();
  const result = JSON.parse(calculate($('sub-csv').value, $('rain-csv').value));   // <-- Java
  if (result.error) {
    $('status').innerHTML = `<span style="color:var(--bad)">Input error: ${result.error}</span>`;
    return;
  }
  $('status').textContent = `Java calculation finished in ${(performance.now() - t0).toFixed(1)} ms.`;
  showCards(result);
  showTimeChart(result);
  showBarChart(result);
  showMap(result);
  show3d(result);
  showTable(result);
}

function showCards(r) {
  const cards = [
    ['Rainfall', fmt(r.totalRainMm), 'mm in ' + r.hours + ' h'],
    ['Total area', fmt(r.totalAreaKm2, 2), 'km²'],
    ['Average runoff', fmt(r.averageRunoffMm), 'mm'],
    ['Runoff volume', fmt(r.totalVolumeM3 / 1e6, 3), 'million m³'],
  ];
  $('cards').innerHTML = cards.map(([l, v, u]) => `<div class="stat"><div class="label">${l}</div><div class="value">${v} <span class="unit">${u}</span></div></div>`).join('');
}

function showTimeChart(r) {
  const labels = r.rain.map((_, h) => h + 1);
  timeChart?.destroy();
  timeChart = new Chart($('chart-time'), {
    data: { labels, datasets: [
      { type: 'bar', label: 'rainfall (mm)', data: r.rain, yAxisID: 'rain', backgroundColor: 'rgba(76,140,220,.5)' },
      { type: 'line', label: 'runoff volume (m³ per hour)', data: r.hourlyVolumeM3, yAxisID: 'vol', borderColor: '#d9480f', pointRadius: 0 },
    ] },
    options: { maintainAspectRatio: false, animation: false, scales: {
      x: { title: { display: true, text: 'hour of the event' } },
      rain: { position: 'right', reverse: true, title: { display: true, text: 'mm' }, grid: { drawOnChartArea: false } },
      vol: { position: 'left', beginAtZero: true, title: { display: true, text: 'm³' } } } },
  });
}

function showBarChart(r) {
  barChart?.destroy();
  barChart = new Chart($('chart-bars'), {
    type: 'bar',
    data: { labels: r.subCatchments.map(s => s.name), datasets: [{ label: 'runoff volume (m³)', data: r.subCatchments.map(s => s.volumeM3), backgroundColor: '#0b6e8a' }] },
    options: { maintainAspectRatio: false, animation: false, indexAxis: 'y', plugins: { legend: { display: false } } },
  });
}

function showMap(r) {
  if (!map) {
    map = L.map('map');
    L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {
      maxZoom: 17, attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors',
    }).addTo(map);
  }
  markers?.remove();
  markers = L.featureGroup();
  const max = Math.max(...r.subCatchments.map(s => s.volumeM3));
  for (const s of r.subCatchments) {
    L.circleMarker([s.lat, s.lon], { radius: 5 + 25 * Math.sqrt(s.volumeM3 / max), color: '#0b6e8a', fillOpacity: 0.45 })
      .bindPopup(`<b>${s.name}</b><br>${fmt(s.areaKm2, 2)} km², CN ${fmt(s.curveNumber)}<br>runoff ${fmt(s.runoffMm)} mm, ${fmt(s.volumeM3, 0)} m³`)
      .addTo(markers);
  }
  markers.addTo(map);
  map.fitBounds(markers.getBounds().pad(0.3));
}

function show3d(r) {
  const el = $('view3d');
  if (!scene3d) {
    const renderer = new THREE.WebGLRenderer({ antialias: true });
    el.appendChild(renderer.domElement);
    const scene = new THREE.Scene();
    scene.background = new THREE.Color(0x0b1720);
    const camera = new THREE.PerspectiveCamera(45, 1, 0.1, 1000);
    camera.position.set(0, 18, 26);
    const controls = new OrbitControls(camera, renderer.domElement);
    scene.add(new THREE.HemisphereLight(0xffffff, 0x334455, 1.2));
    const sun = new THREE.DirectionalLight(0xffffff, 1.5); sun.position.set(10, 20, 10); scene.add(sun);
    scene.add(new THREE.GridHelper(30, 30, 0x335566, 0x223344));
    const group = new THREE.Group(); scene.add(group);
    const resize = () => { const w = el.clientWidth, h = el.clientHeight; renderer.setSize(w, h, false); camera.aspect = w / h; camera.updateProjectionMatrix(); };
    new ResizeObserver(resize).observe(el); resize();
    (function loop() { controls.update(); renderer.render(scene, camera); requestAnimationFrame(loop); })();
    scene3d = { group };
  }
  const g = scene3d.group;
  g.clear();
  const lat0 = r.subCatchments.reduce((a, s) => a + s.lat, 0) / r.subCatchments.length;
  const lon0 = r.subCatchments.reduce((a, s) => a + s.lon, 0) / r.subCatchments.length;
  const maxDepth = Math.max(...r.subCatchments.map(s => s.runoffMm));
  for (const s of r.subCatchments) {
    const h = 10 * s.runoffMm / maxDepth, w = 0.6 * Math.sqrt(s.areaKm2);
    const bar = new THREE.Mesh(new THREE.BoxGeometry(w, h, w), new THREE.MeshLambertMaterial({ color: new THREE.Color().setHSL(0.55, 0.7, 0.35 + 0.3 * s.runoffMm / maxDepth) }));
    // 1 degree of latitude ~ 111 km; 1 unit = 1 km
    bar.position.set((s.lon - lon0) * 111 * Math.cos(lat0 * Math.PI / 180), h / 2, -(s.lat - lat0) * 111);
    g.add(bar);
  }
}

function showTable(r) {
  $('table').innerHTML = '<thead><tr><th>Sub-catchment</th><th>Area (km²)</th><th>CN</th><th>S (mm)</th><th>Runoff (mm)</th><th>Runoff coefficient</th><th>Volume (m³)</th></tr></thead><tbody>' +
    r.subCatchments.map(s => `<tr><td>${s.name}</td><td>${fmt(s.areaKm2, 3)}</td><td>${fmt(s.curveNumber)}</td><td>${fmt(s.retentionMm)}</td>` +
      `<td>${fmt(s.runoffMm)}</td><td>${fmt(s.runoffCoefficient, 2)}</td><td>${fmt(s.volumeM3, 0)}</td></tr>`).join('') + '</tbody>';
}

$('calculate').addEventListener('click', run);
$('reload').addEventListener('click', async () => { await loadSamples(); run(); });
readFileInto($('sub-file'), $('sub-csv'));
readFileInto($('rain-file'), $('rain-csv'));
await loadSamples();
run();
