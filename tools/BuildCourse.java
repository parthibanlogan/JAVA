import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Prepares the course programs for the website.
 *
 * <pre>
 *   java tools/BuildCourse.java --course course --gen DIR        # Java sources for the TeaVM build
 *   java tools/BuildCourse.java --course course --site DIR       # catalog.json + files for the site
 * </pre>
 *
 * --gen copies every program that can run in the browser into its own package (course.l01,
 * course.e06a, ...) so that classes with the same name (Main, Rectangle, ...) do not clash, and
 * writes lab/web/CourseRegistry.java, which starts a program by its id. The program text is
 * not changed apart from the added package line.
 *
 * --site writes catalog.json and copies README.md, the .java files, inputs and expected outputs.
 */
public class BuildCourse {

    record Program(String id, String folder, String group, Properties meta, Path dir) { }

    public static void main(String[] args) throws Exception {
        Path course = Paths.get("course");
        Path gen = null, site = null;
        for (int i = 0; i < args.length; i++) {
            switch (args[i]) {
                case "--course": course = Paths.get(args[++i]); break;
                case "--gen": gen = Paths.get(args[++i]); break;
                case "--site": site = Paths.get(args[++i]); break;
                default: throw new IllegalArgumentException("unknown option " + args[i]);
            }
        }
        List<Program> programs = load(course);
        if (gen != null) generateSources(programs, gen);
        if (site != null) writeSite(programs, site);
    }

    static List<Program> load(Path course) throws IOException {
        List<Program> list = new ArrayList<>();
        for (String group : new String[] {"lessons", "experiments"}) {
            List<Path> dirs;
            try (Stream<Path> s = Files.list(course.resolve(group))) {
                dirs = s.filter(p -> Files.exists(p.resolve("meta.properties"))).sorted().collect(Collectors.toList());
            }
            for (Path d : dirs) {
                Properties meta = new Properties();
                try (InputStream in = Files.newInputStream(d.resolve("meta.properties"))) {
                    meta.load(new java.io.InputStreamReader(in, StandardCharsets.UTF_8));
                }
                String folder = d.getFileName().toString();
                list.add(new Program(folder.substring(0, folder.indexOf('-')), folder, group, meta, d));
            }
        }
        return list;
    }

    static String adapt(String source, String pkg) {
        return "package " + pkg + ";\n" + source;
    }

    static void generateSources(List<Program> programs, Path gen) throws IOException {
        StringBuilder sw = new StringBuilder();
        for (Program p : programs) {
            if (!"true".equals(p.meta().getProperty("browser"))) continue;
            String pkg = "course." + p.id().toLowerCase();
            Path out = gen.resolve(pkg.replace('.', '/'));
            Files.createDirectories(out);
            try (Stream<Path> s = Files.list(p.dir())) {
                for (Path src : (Iterable<Path>) s.filter(f -> f.toString().endsWith(".java"))::iterator) {
                    String text = Files.readString(src, StandardCharsets.UTF_8);
                    Files.writeString(out.resolve(src.getFileName()), adapt(text, pkg), StandardCharsets.UTF_8);
                }
            }
            String main = p.meta().getProperty("main", "Main");
            sw.append("            case \"").append(p.id()).append("\": ").append(pkg).append('.').append(main)
              .append(".main(new String[0]); return true;\n");
        }
        Path reg = gen.resolve("lab/web");
        Files.createDirectories(reg);
        Files.writeString(reg.resolve("CourseRegistry.java"),
                "package lab.web;\n\n/** Generated by tools/BuildCourse.java. Do not edit. */\n"
                + "final class CourseRegistry {\n    private CourseRegistry() { }\n\n"
                + "    static boolean run(String id) throws Exception {\n        switch (id) {\n" + sw
                + "            default: return false;\n        }\n    }\n}\n", StandardCharsets.UTF_8);
    }

    static String json(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"': b.append("\\\""); break;
                case '\\': b.append("\\\\"); break;
                case '\n': b.append("\\n"); break;
                default: if (c < 0x20) b.append(String.format("\\u%04x", (int) c)); else b.append(c);
            }
        }
        return b.append('"').toString();
    }

    static void writeSite(List<Program> programs, Path site) throws IOException {
        StringBuilder cat = new StringBuilder("[\n");
        for (int i = 0; i < programs.size(); i++) {
            Program p = programs.get(i);
            Path out = site.resolve(p.group()).resolve(p.folder());
            Files.createDirectories(out);
            List<String> files = new ArrayList<>();
            List<String> cases = new ArrayList<>();
            try (Stream<Path> s = Files.list(p.dir())) {
                for (Path f : (Iterable<Path>) s.sorted()::iterator) {
                    String name = f.getFileName().toString();
                    if (name.endsWith(".java") || name.endsWith(".md") || name.endsWith(".txt") || name.endsWith(".sql")) {
                        Files.copy(f, out.resolve(name), StandardCopyOption.REPLACE_EXISTING);
                        if (name.endsWith(".java")) files.add(name);
                        if (name.startsWith("expected")) cases.add(name.substring("expected".length(), name.length() - 4));
                    }
                }
            }
            Properties m = p.meta();
            cat.append("  {\"id\":").append(json(p.id()))
               .append(",\"kind\":").append(json(m.getProperty("kind")))
               .append(",\"title\":").append(json(m.getProperty("title")))
               .append(",\"path\":").append(json(p.group() + "/" + p.folder()))
               .append(",\"browser\":").append("true".equals(m.getProperty("browser")))
               .append(",\"requires\":").append(json(m.getProperty("requires", "")))
               .append(",\"javacNote\":").append(json(m.getProperty("javacNote", "")))
               .append(",\"note\":").append(json(m.getProperty("browserNote", "")))
               .append(",\"sources\":[").append(files.stream().map(BuildCourse::json).collect(Collectors.joining(",")))
               .append("],\"cases\":[").append(cases.stream().map(BuildCourse::json).collect(Collectors.joining(",")))
               .append("]}").append(i + 1 < programs.size() ? ",\n" : "\n");
        }
        cat.append("]\n");
        Files.createDirectories(site);
        Files.writeString(site.resolve("catalog.json"), cat.toString(), StandardCharsets.UTF_8);
    }
}
